import type { HypothesisResult } from "./types";

export function toMarkdown(r: HypothesisResult): string {
  const L: string[] = [];
  L.push(`# HYPOGEN report`, ``, `**Question:** ${r.question}`, ``);
  L.push(`## Verdict`, ``, `**${r.summary.headline}**`, ``);
  r.summary.key_points.forEach((k) => L.push(`- ${k}`));
  L.push(``, `## Candidate hypothesis (untested, not a finding)`, ``);
  L.push(`- Prediction: ${r.prediction}`, `- Drafted by: ${r.drafter}`, `- Assumption: ${r.assumption}`, ``);
  L.push(`## Premises and evidence`, ``);
  r.premises.forEach((p) => {
    L.push(`### [${p.label.toUpperCase()}] ${p.premise}`);
    L.push(`Cited: ${p.cited.id}, ${p.cited.paper}, p.${p.cited.page}`, ``);
    if (p.evidence.length === 0) L.push(`- No other passage in this corpus bears on this premise.`);
    p.evidence.forEach((e) => L.push(`- (${e.relation}, ${e.id}, similarity ${e.similarity}) ${e.text}`));
    L.push(``);
  });
  L.push(`## Experiment plan`, ``);
  Object.entries(r.experiment).forEach(([k, v]) => L.push(`- ${k.replace("_", " ")}: ${v || "**MISSING**"}`));
  L.push(``, `## Warnings`, ``);
  r.warnings.forEach((w) => L.push(`- ${w}`));
  L.push(``, `## Next actions`, ``);
  r.summary.next_actions.forEach((a) => L.push(`- ${a}`));
  L.push(``, `---`, `Generated by the HYPOGEN demo. Retrieval is TF-IDF and the checker is a lexical baseline.`);
  return L.join("\n");
}

export function downloadText(filename: string, text: string) {
  const url = URL.createObjectURL(new Blob([text], { type: "text/markdown" }));
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}
